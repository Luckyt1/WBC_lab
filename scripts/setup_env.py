"""Prepare isolated environments, or reuse explicitly supplied interpreters."""
import argparse
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.runtime_env import ROOT, environment, project_path


def run(command):
    print('+', shlex.join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), cwd=ROOT, check=True)


def interpreter(value):
    found = shutil.which(value)
    path = Path(found).absolute() if found else project_path(value)
    if not path.is_file():
        raise ValueError(f'Python not found: {value}')
    # Do not resolve symlinks: venv interpreters must keep their own sys.prefix.
    run([path, '-c', 'import sys; assert sys.version_info[:2] == (3, 11), "Python 3.11 required"'])
    return path


def new_env(base, name):
    path = ROOT / f'.venv-{name}'
    if not (path / 'bin/python').is_file():
        if path.exists() and any(path.iterdir()):
            raise ValueError(f'Not an empty venv destination: {path}')
        run([base, '-m', 'venv', path])
    python = path / 'bin/python'
    run([python, '-m', 'pip', 'install', '--upgrade', 'pip'])
    return python


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--python', default='python3.11', help='Base Python 3.11 for new environments')
    p.add_argument('--train-python', help='Reuse an existing Isaac Python; installs nothing into it')
    p.add_argument('--deployment-python', help='Reuse an existing CPU evaluation Python')
    p.add_argument('--ik-python', help='Reuse an existing Pinocchio Python')
    p.add_argument('--force-env', action='store_true', help='Replace .env, preserving .env.backup')
    args = p.parse_args()
    if platform.system() != 'Linux' or platform.machine() not in ('x86_64', 'AMD64'):
        p.error('This bootstrap targets Linux x86_64 with NVIDIA CUDA.')
    if (ROOT / '.env').exists() and not args.force_env:
        p.error('.env already exists. Use ./deploy.sh check, or --force-env to reconfigure.')
    if not shutil.which('c++'):
        p.error('Missing C++17 compiler. Install build-essential first.')
    base = interpreter(args.train_python or args.python)
    if args.train_python:
        train = base
    else:
        train = new_env(base, 'train')
        run([train, '-m', 'pip', 'install', 'torch==2.7.0', 'torchvision==0.22.0',
             '--index-url', 'https://download.pytorch.org/whl/cu128'])
        run([train, '-m', 'pip', 'install', 'isaacsim[all,extscache]==5.0.0',
             '--extra-index-url', 'https://pypi.nvidia.com', '-c', ROOT/'requirements/train-constraints.txt'])
        run([train, '-m', 'pip', 'install', '-r', ROOT/'requirements/train.txt',
             '-c', ROOT/'requirements/train-constraints.txt'])
    interpreters = {'train': train}
    for role, supplied, requirements in [('eval', args.deployment_python, 'eval.txt'),
                                          ('ik', args.ik_python, 'ik.txt')]:
        if supplied:
            interpreters[role] = interpreter(supplied)
        else:
            python = new_env(base, role)
            run([python, '-m', 'pip', 'install', 'torch==2.7.0', '--index-url',
                 'https://download.pytorch.org/whl/cpu'])
            run([python, '-m', 'pip', 'install', '-r', ROOT/'requirements'/requirements])
            interpreters[role] = python
    # Source paths are supplied per process; never replace a running editable install.
    subprocess.run([str(train), 'tools/build_arm_ruckig.py'], cwd=ROOT, env=environment(), check=True)
    env_path = ROOT / '.env'
    if env_path.exists():
        shutil.copy2(env_path, ROOT / '.env.backup')
    lines = ['# Generated by deploy.sh setup; resources resolve relative to this checkout.']
    for role, key in [('train', 'ELF3_TRAIN_PYTHON'), ('eval', 'ELF3_DEPLOYMENT_PYTHON'), ('ik', 'ELF3_IK_PYTHON')]:
        value = interpreters[role]
        try:
            value = value.relative_to(ROOT)
        except ValueError:
            pass
        lines.append(key + '=' + shlex.quote(str(value)))
    resources = {'ELF3_ASSET_DIR': 'resources/elf3_bxi_31',
                 'ELF3_BXI_FRAMEWORK_DIR': 'resources/bxi_example_py_elf3',
                 'ELF3_MUJOCO_XML': 'resources/bxi_example_py_elf3/data/mujoco_simulation/elf3.xml',
                 'ELF3_IK_SOURCE_DIR': 'resources/elf3_ik_upstream',
                 'ELF3_IK_BANK': 'resources/ik_bank_v3', 'ELF3_AMASS_DIR': 'resources/dataset'}
    for key, default in resources.items():
        lines.append(key + '=' + shlex.quote(os.environ.get(key, default)))
    env_path.write_text('\n'.join(lines) + '\n')
    # Discard old interpreter settings loaded by the outer dispatcher.
    clean = environment()
    for key, role in [('ELF3_TRAIN_PYTHON', 'train'), ('ELF3_DEPLOYMENT_PYTHON', 'eval'), ('ELF3_IK_PYTHON', 'ik')]:
        clean[key] = str(interpreters[role])
    result = subprocess.run([sys.executable, 'scripts/doctor.py'], cwd=ROOT, env=clean)
    raise SystemExit(result.returncode)


if __name__ == '__main__':
    main()
